#!/usr/bin/env python3

"""Nimbus pre-launch population sizing ETL.

Fetches Draft experiments from the Experimenter v8 API, executes their
translated BigQuery SQL WHERE clauses against per-app pre-materialized
client pool tables, and writes per-experiment eligible-client estimates
to GCS and BigQuery.

The per-app client pools (nimbus_sizing_clients_v1) are generated by the
experiment_monitoring sql_generator and populated daily by
bqetl_experiments_daily.
Each partition contains a 7-day rolling window of deduplicated, 10%-sampled
clients with all targeting context columns already typed and extracted, so this
script only needs to generate and run COUNTIF queries.

Partitions overlap: each is an independently deduplicated 7-day window, so a
client appears in most of the 14 live partitions. Queries must therefore pin a
single partition, or every client is counted once per partition.

Supports Desktop (firefox_desktop), Fenix (fenix), and iOS (firefox_ios).
"""

import json
import logging
from argparse import ArgumentParser
from datetime import date, datetime, timezone

import requests
from google.cloud import bigquery, storage  # type: ignore

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

EXPERIMENTER_API_URL = (
    "https://experimenter.services.mozilla.com/api/v8/draft-experiments/"
)
GCS_BUCKET = "mozanalysis"
GCS_FOLDER = "population_sizing"
# 10% sample -- multiply counts by 10 to estimate full population.
SAMPLE_ID_MAX = 10

_APP_SIZING_TABLE: dict[str, str] = {
    "firefox_desktop": "moz-fx-data-shared-prod.firefox_desktop_derived.nimbus_sizing_clients_v1",
    "fenix": "moz-fx-data-shared-prod.org_mozilla_fenix_derived.nimbus_sizing_clients_v1",
    "firefox_ios": "moz-fx-data-shared-prod.org_mozilla_ios_firefox_derived.nimbus_sizing_clients_v1",
}

# normalized_channel values each app's targeting-context ping actually carries.
# Desktop additionally ships esr and aurora; the mobile pings do not. An
# experiment channel outside its app's set (e.g. mobile "developer") has no
# corresponding client population, so the filter is dropped rather than forcing
# a zero.
_KNOWN_CHANNELS: dict[str, frozenset[str]] = {
    "firefox_desktop": frozenset({"release", "beta", "nightly", "esr", "aurora"}),
    "fenix": frozenset({"release", "beta", "nightly"}),
    "firefox_ios": frozenset({"release", "beta", "nightly"}),
}

parser = ArgumentParser(description=__doc__)
parser.add_argument("--date", required=True, help="Execution date (YYYY-MM-DD)")
parser.add_argument("--project", default="moz-fx-data-experiments")
parser.add_argument("--output-dataset", default="monitoring")
parser.add_argument("--output-table", default="experiment_population_estimates_v1")
parser.add_argument("--api-url", default=EXPERIMENTER_API_URL)
parser.add_argument("--gcs-bucket", default=GCS_BUCKET)
parser.add_argument("--gcs-folder", default=GCS_FOLDER)
parser.add_argument(
    "--dry-run",
    action="store_true",
    help="Print queries without running",
)


def fetch_experiments(api_url: str) -> list:
    """Fetch Draft experiments that need a sizing update from Experimenter."""
    resp = requests.get(api_url, timeout=30)
    resp.raise_for_status()
    payload = resp.json()
    if not isinstance(payload, list):
        raise RuntimeError(
            f"Unexpected response from {api_url}: "
            f"expected list, got {type(payload).__name__}"
        )
    return [
        exp
        for exp in payload
        if exp.get("targetingSql")
        and exp["targetingSql"].get("needsUpdate")
        and exp["targetingSql"].get("sql")
    ]


def _col_for_index(i: int) -> str:
    """Return a stable, unique BigQuery column alias for experiment index i."""
    return f"exp_{i}"


def _channels_for(exp: dict, app_name: str) -> list[str]:
    """Return the normalized_channel values to constrain an experiment to.

    Reads `channels`, not `channel`. The v8 serializer treats `channels` as
    canonical and only falls back to `[channel]` when it is unset, so an
    experiment targeting several channels lists them all there and may leave
    the singular field empty.

    Channels this app's ping never emits (e.g. mobile "developer") are dropped
    — they have no client population, so including them would change nothing.
    An empty result means "do not constrain on channel" rather than "match
    nothing", so an all-unknown experiment is not forced to zero.
    """
    channels = exp.get("channels")
    if not channels:
        channels = [exp["channel"]] if exp.get("channel") else []
    known = _KNOWN_CHANNELS.get(app_name, frozenset())
    return sorted({c.strip().lower() for c in channels if c} & known)


def latest_pool_partition(table: str, project: str) -> str | None:
    """Return the newest populated partition of the pool table as YYYY-MM-DD.

    Resolved from INFORMATION_SCHEMA rather than the DAG's execution date: the
    pool is built by a separate daily DAG that this job deliberately does not
    wait on, so the partition for {{ ds }} may not exist yet. Pinning the newest
    partition that does exist keeps an early run correct instead of silently
    sizing against nothing.

    Requires total_rows > 0: an empty partition would otherwise win MAX and
    size every experiment for that app at zero. The date-shaped filter skips
    the sentinel partition ids, which sort above real dates.
    """
    table_project, dataset, table_name = table.split(".")
    sql = f"""
        SELECT MAX(partition_id) AS partition_id
        FROM `{table_project}.{dataset}.INFORMATION_SCHEMA.PARTITIONS`
        WHERE table_name = '{table_name}'
          AND REGEXP_CONTAINS(partition_id, r'^[0-9]{{8}}$')
          AND total_rows > 0
    """
    client = bigquery.Client(project=project)
    rows = list(client.query(sql).result())
    partition_id = rows[0]["partition_id"] if rows else None
    if not partition_id:
        return None
    return f"{partition_id[:4]}-{partition_id[4:6]}-{partition_id[6:]}"


def build_query(experiments: list, app_name: str, pool_date: str) -> str:
    """Build a single BigQuery COUNTIF query against the per-app client pool.

    Pinned to one partition. Each partition is an independently deduplicated
    7-day window and the table keeps 14 of them, so an unpinned scan counts
    every client once per partition it appears in.

    Channel is applied per COUNTIF rather than in the WHERE clause, because one
    query batches every experiment for an app and they do not share a channel.
    Mobile targeting SQL carries no channel predicate of its own, so without
    this a nightly rollout is sized against the release population.

    Uses indexed column aliases (exp_0, exp_1, ...) to avoid slug-to-column
    collisions. One COUNTIF per experiment in a single table scan.
    """
    table = _APP_SIZING_TABLE[app_name]
    cols = []
    for i, exp in enumerate(experiments):
        predicate = exp["targetingSql"]["sql"]
        channels = _channels_for(exp, app_name)
        if channels:
            rendered = ", ".join(f"'{c}'" for c in channels)
            predicate = f"normalized_channel IN ({rendered})\n    AND ({predicate})"
        cols.append(
            f"  COUNTIF(\n    {predicate}\n"
            f"  ) * {SAMPLE_ID_MAX} AS `{_col_for_index(i)}`"
        )
    return (
        "SELECT\n"
        + ",\n".join(cols)
        + f"\nFROM `{table}`\nWHERE _PARTITIONDATE = '{pool_date}'"
    )


def _dry_run_sql(sql: str, project: str, app_name: str) -> bool:
    """Return True if sql is a valid BigQuery expression, False otherwise."""
    table = _APP_SIZING_TABLE[app_name]
    probe = f"SELECT COUNTIF({sql}) AS c FROM `{table}` WHERE FALSE"
    try:
        client = bigquery.Client(project=project)
        job_config = bigquery.QueryJobConfig(dry_run=True, use_query_cache=False)
        client.query(probe, job_config=job_config)
        return True
    except Exception as exc:
        logger.warning("SQL dry-run failed: %s", exc)
        return False


def build_results(
    experiments: list,
    query: str,
    project: str,
    platform: str = "firefox_desktop",
) -> dict:
    """Execute query and map results back to per-experiment result dicts.

    Uses positional index aliases (exp_0, exp_1, ...) to avoid slug collisions.
    """
    client = bigquery.Client(project=project)
    rows = [dict(row) for row in client.query(query).result()]

    if not rows:
        return {}

    row = rows[0]
    results = {}
    for i, exp in enumerate(experiments):
        col = _col_for_index(i)
        eligible_count = row.get(col)
        if eligible_count is None:
            continue
        results[exp["slug"]] = {
            "platform": platform,
            "eligible_count": int(eligible_count),
            "warnings": exp["targetingSql"].get("warnings", []),
        }
    return results


def write_to_gcs(results: dict, bucket_name: str, folder: str, run_date: str) -> None:
    """Write versioned sizing results to GCS for Experimenter to read.

    Writes two files:
      - experiment_population_estimates_v1_{date}.json  -- dated archive
      - experiment_population_estimates_v1_latest.json  -- consumed by Experimenter
    """
    client = storage.Client()
    bucket = client.bucket(bucket_name)
    json_str = json.dumps({"v1": results}, indent=2)

    dated_path = f"{folder}/experiment_population_estimates_v1_{run_date}.json"
    bucket.blob(dated_path).upload_from_string(
        json_str, content_type="application/json"
    )
    logger.info("Wrote sizing results to gs://%s/%s", bucket_name, dated_path)

    latest_path = f"{folder}/experiment_population_estimates_v1_latest.json"
    bucket.copy_blob(bucket.blob(dated_path), bucket, latest_path)
    logger.info("Copied to gs://%s/%s", bucket_name, latest_path)


def write_to_bigquery(
    results: dict,
    project: str,
    dataset: str,
    table: str,
    submission_date: date,
) -> None:
    """Write sizing results to BigQuery, appending to the date partition.

    Appends rather than truncates because each run only sizes the experiments
    flagged needsUpdate at that moment. Truncating would drop estimates written
    by earlier runs the same day. Every row carries computed_at, so consumers
    take the latest row per slug.
    """
    client = bigquery.Client(project=project)
    computed_at = datetime.now(timezone.utc)
    rows = [
        {
            "slug": slug,
            "platform": data["platform"],
            "eligible_count": data["eligible_count"],
            "warnings": data["warnings"],
            "computed_at": computed_at.isoformat(),
        }
        for slug, data in results.items()
    ]
    if not rows:
        return

    partition_decorator = computed_at.strftime("%Y%m%d")
    table_ref = f"{project}.{dataset}.{table}${partition_decorator}"
    job_config = bigquery.LoadJobConfig(
        write_disposition=bigquery.WriteDisposition.WRITE_APPEND,
        schema=[
            bigquery.SchemaField("slug", "STRING", mode="REQUIRED"),
            bigquery.SchemaField("platform", "STRING"),
            bigquery.SchemaField("eligible_count", "INTEGER"),
            bigquery.SchemaField("warnings", "STRING", mode="REPEATED"),
            bigquery.SchemaField("computed_at", "TIMESTAMP", mode="REQUIRED"),
        ],
    )
    job = client.load_table_from_json(rows, table_ref, job_config=job_config)
    job.result()
    logger.info("Wrote %d rows to %s", len(rows), table_ref)


def main():
    """Run Nimbus pre-launch population sizing ETL."""
    args = parser.parse_args()
    run_date = date.fromisoformat(args.date)

    all_experiments = fetch_experiments(args.api_url)
    logger.info("Found %d experiments needing sizing update", len(all_experiments))

    if not all_experiments:
        logger.info("No experiments to process")
        return

    platform_groups: dict[str, list] = {}
    for exp in all_experiments:
        app_name = exp.get("appName", "firefox_desktop")
        if app_name not in _APP_SIZING_TABLE:
            logger.warning("Unknown appName %r for %s, skipping", app_name, exp["slug"])
            continue
        platform_groups.setdefault(app_name, []).append(exp)

    all_results: dict = {}
    has_valid = False

    for app_name, experiments in platform_groups.items():
        try:
            pool_date = latest_pool_partition(
                _APP_SIZING_TABLE[app_name], project=args.project
            )
            if pool_date is None:
                logger.error("No populated partition in %s pool, skipping", app_name)
                continue
            logger.info("Sizing %s against pool partition %s", app_name, pool_date)

            valid_experiments = []
            for exp in experiments:
                sql = exp["targetingSql"]["sql"]
                if _dry_run_sql(sql, project=args.project, app_name=app_name):
                    valid_experiments.append(exp)
                else:
                    logger.warning(
                        "Skipping %s -- SQL failed dry-run validation", exp["slug"]
                    )

            if not valid_experiments:
                continue

            has_valid = True
            query = build_query(
                valid_experiments, app_name=app_name, pool_date=pool_date
            )

            if args.dry_run:
                print(f"-- {app_name}\n{query}")
                continue

            results = build_results(
                valid_experiments, query, project=args.project, platform=app_name
            )
            logger.info(
                "Got sizing results for %d %s experiments", len(results), app_name
            )
            all_results.update(results)
        except Exception as exc:
            logger.error("Platform %s sizing failed, skipping: %s", app_name, exc)

    if args.dry_run:
        return

    if not has_valid:
        logger.info("No valid experiments after dry-run validation")
        return

    write_to_gcs(
        all_results,
        bucket_name=args.gcs_bucket,
        folder=args.gcs_folder,
        run_date=args.date,
    )
    write_to_bigquery(
        all_results,
        project=args.project,
        dataset=args.output_dataset,
        table=args.output_table,
        submission_date=run_date,
    )
    logger.info("Population sizing ETL complete")


if __name__ == "__main__":
    main()
